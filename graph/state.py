from typing import (
    TypedDict,
    List,
    Dict,
    Any
)


class ResearchState(
    TypedDict,
    total=False
):

    # --------------------------------------------------------
    # Research input
    # --------------------------------------------------------

    topic: str

    # --------------------------------------------------------
    # Academic papers
    # --------------------------------------------------------

    papers: List[
        Dict[str, Any]
    ]

    # --------------------------------------------------------
    # Extracted paper corpus
    # --------------------------------------------------------

    corpus: List[
        Dict[str, Any]
    ]

    # --------------------------------------------------------
    # Evidence chunks
    # --------------------------------------------------------

    evidence_chunks: List[
        Dict[str, Any]
    ]

    # --------------------------------------------------------
    # LLM outputs
    # --------------------------------------------------------

    research_draft: str

    critic_feedback: str

    final_report: str

    # --------------------------------------------------------
    # Pipeline errors
    # --------------------------------------------------------

    errors: List[str]